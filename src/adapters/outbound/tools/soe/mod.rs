/// Refusal without `[sources]` (module table: state root).
pub(crate) const SOE_STATE_MISSING: &str = "soe_state_missing";
/// A write by an agent whose name no env names (module table).
pub(crate) const STAGE_AGENT_UNKNOWN: &str = "stage_agent_unknown";
/// A write by an agent that is not the `[soe]` stage's.
pub(crate) const STAGE_AGENT_MISMATCH: &str = "stage_agent_mismatch";
/// Largest text a tool returns, in bytes: ≤ 3/4 of a 16k-window local
/// model's 8 192-char result cap (`engines/local.rs`), as the xlab and source
/// tools keep.
pub(crate) const TEXT_BUDGET: usize = 6_000;

/// Who calls, as the stamp needs it (module table: stage agent, provenance).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Stamp {
    /// The calling agent's name; `None` = no env names it.
    pub agent: Option<String>,
    pub model: String,
    pub engine: String,
    /// The agent's skill packages, for `skill_sha256`.
    pub skill_packages: Vec<String>,
    /// Where its skills are found (`runner::skill_sha256`).
    pub workspace: std::path::PathBuf,
    /// The step's own skill identity (`runner::SKILL_SHA256_ENV`, exported
    /// by `run-agent`); `None` = computed from `skill_packages` here.
    pub step_skill_sha256: Option<String>,
    /// `[generation] id`, else `UNBOUND`.
    pub generation: String,
}

impl Stamp {
    /// The stamp of the agent a plugin is built for (module table).
    fn of(config: &AgentConfig, workspace: &Path, agent: Option<String>) -> Self {
        Stamp {
            agent,
            step_skill_sha256: std::env::var(SKILL_SHA256_ENV)
                .ok()
                .filter(|s| crate::domain::evidence::valid_sha256(s)),
            model: config.model.clone(),
            engine: config.engine.clone(),
            skill_packages: config.skill_packages.clone(),
            workspace: config
                .workspace
                .as_deref()
                .map(expand_tilde)
                .unwrap_or_else(|| workspace.to_path_buf()),
            generation: config
                .sandbox
                .generation
                .as_ref()
                .map_or_else(|| UNBOUND.to_string(), |g| g.id.clone()),
        }
    }

    /// The stage agent's name, or the refusal; with `[soe]`, it must be
    /// `want` (`soe.architect` / `soe.critic`).
    pub(crate) fn check_agent(&self, tool: &str, want: Option<&str>) -> Result<&str> {
        let Some(name) = self.agent.as_deref() else {
            bail!(
                "{STAGE_AGENT_UNKNOWN}: {tool} writes from a stage run — no TENGU_AGENT_NAME (a \
                 `run-agent` step sets it) and no TENGU_BRIDGE_AGENT name the calling agent"
            );
        };
        if let Some(want) = want.filter(|w| *w != name) {
            bail!(
                "{STAGE_AGENT_MISMATCH}: {tool} is the stage tool of [agents.{want}] ([soe]); \
                 `{name}` called it"
            );
        }
        Ok(name)
    }

    /// The provenance of one write by `agent` (module table).
    pub(crate) fn provenance(&self, agent: &str, call_id: Option<&str>, now_ms: i64) -> Provenance {
        Provenance {
            agent: agent.to_string(),
            model: self.model.clone(),
            engine: self.engine.clone(),
            skill_sha256: self
                .step_skill_sha256
                .clone()
                .unwrap_or_else(|| skill_sha256_of(&self.skill_packages, &self.workspace)),
            generation: self.generation.clone(),
            call_id: call_id
                .filter(|c| !c.trim().is_empty())
                .unwrap_or("UNKNOWN")
                .to_string(),
            proposed_at: Time::At(now_ms),
        }
    }
}

/// Handles every family tool shares.
#[derive(Clone)]
pub(crate) struct SoeShared {
    /// The cycle store on the state root, or the refusal (module table).
    pub store: Result<Arc<dyn CycleStore>, String>,
    /// The sandbox's sections (`[soe]`, `[generation]`).
    pub sandbox: Arc<SandboxSections>,
    pub clock: Arc<dyn Clock>,
    pub stamp: Stamp,
}

impl SoeShared {
    pub(crate) fn store(&self) -> Result<&dyn CycleStore> {
        match &self.store {
            Ok(s) => Ok(s.as_ref()),
            Err(why) => Err(anyhow!("{why}")),
        }
    }
}

/// The state root's store of `sections`, or the refusal (module table).
pub(crate) fn open_store(sections: &SandboxSections) -> Result<Arc<dyn CycleStore>, String> {
    sections
        .sources_state_dir
        .as_ref()
        .map(|root| Arc::new(FsCycleStore::new(root)) as Arc<dyn CycleStore>)
        .ok_or_else(|| {
            format!(
                "{SOE_STATE_MISSING}: no [sources] section — the SOE state root (cycles, replays, \
                 logs) is <TENGU_HOME>/state/<sources.state>/; add [sources] state = \"<name>\""
            )
        })
}

/// The calling agent's name from the env (module table: stage agent).
fn agent_from_env() -> Option<String> {
    ["TENGU_AGENT_NAME", "TENGU_BRIDGE_AGENT"]
        .iter()
        .filter_map(|k| std::env::var(k).ok())
        .map(|v| v.trim().to_string())
        .find(|v| !v.is_empty())
}

