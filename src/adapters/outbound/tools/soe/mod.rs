//! SOE tool family (O3; `docs/soe-2026-10-08.md` § 13) — the weekly cycle's
//! stage tools over the private SOE state root
//! `<TENGU_HOME>/state/<sources.state>/` (critic C8, `outbound/soe/store.rs`).
//! The Architect reads its cycle and proposes; the Critic reads and
//! challenges. Every check and every id is the application's
//! (`application::soe::submit`); a tool never writes a file itself. Nothing
//! here contacts anyone, spends, publishes or deploys. One opt-in catalog row
//! per tool; interfaces live in [`defs`].
//!
//! | File | Tool |
//! |---|---|
//! | `view.rs` | `soe_view` — `soe_view/1:<run>:<view>`, read-only: the run's `head` (phase, limits, counts), its `packet` (the O2 evidence packet at the decision, paged, source text fenced), the week's `candidates` (new + carried, each with its inputs and bases), this run's `proposals` / `challenges`, and `history` (the `OpportunityEpisode`s of earlier cycles decided before this run — critic UNCOVERED 5) |
//! | `propose.rs` | `soe_propose` — one Architect draft through `submit::submit_proposal` (open run, `PROPOSE` phase, every check listed), stamped `<cycle>.pNN`; returns the id and a read-only preview (`rank::assess` of the draft under the run's profile at the decision: gates, rank keys) |
//! | `challenge.rs` | `soe_challenge` — one Critic draft, flat arguments, through `submit::submit_challenge` (`CHALLENGE` phase), stamped `<cycle>.cNN` |
//! | `tests.rs` | the tools inside a real `run_cycle` (in-memory and on-disk stores), the fixture state root `tests/fixtures/soe/state/` (regenerated by its test) |
//!
//! | Rule | Value |
//! |---|---|
//! | State root | `SandboxSections::sources_state_dir` (`[sources]`); none ⇒ every tool refuses `soe_state_missing`. `FsCycleStore` on it; nothing is created by a read |
//! | Run | the `run` argument = the goal's `run:` line (`cycles/<id>` · `replays/<id>`, `ports::soe::RunDir::parse`); a review dir or another text is refused |
//! | Scope | `fs_roots` = the workspace (`check_fs_write` / `check_fs_read` on it, as the xlab tools): the state root sits outside every fs root by design (load rule) — the tools' own state, never an agent path. No network, no env |
//! | Stage agent | the calling agent's name = `TENGU_AGENT_NAME` (a `run-agent` step; its bridge inherits it), else `TENGU_BRIDGE_AGENT`, read once when the plugin is built; a write with none is refused (`stage_agent_unknown`). With `[soe]`: `soe_propose` only as `soe.architect`, `soe_challenge` only as `soe.critic` (`stage_agent_mismatch`) |
//! | Provenance ([`Stamp::provenance`]) | `agent` (above) · `model` / `engine` (the agent's block) · `skill_sha256` = the step's own (`runner::SKILL_SHA256_ENV`, exported by `run-agent` from the cwd the stage cache key sees — a Claude Code bridge runs in the workspace and inherits it), else `runner::skill_sha256_of` over the agent's skill packages (its `workspace`, else the tool's) — the stage cache key's own identity · `generation` = the bound `[generation]` id, else `UNBOUND` (`submit::UNBOUND`; the cycle refuses another, `generation_mismatch`) · `call_id` (`UNKNOWN` without one) · `proposed_at` = now |
//! | Refusals | `submit_*`'s codes, one line each (`stage_closed`, `computed_field`, `unsupported_evidence`, `duplicate`, …) — the tool errors; nothing is written |
//! | Text | ≤ [`TEXT_BUDGET`] bytes (a 16k local model's result cap); ids and hashes in full; model and source text only inside a `source-text` fence after one note |

