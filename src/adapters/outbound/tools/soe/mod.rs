/// The `run` argument as a cycle or replay dir (module table: run).
pub(crate) fn run_arg(tool: &str, o: &Map<String, Value>) -> Result<RunDir> {
    let text = opt_str(tool, o, "run")?.ok_or_else(|| {
        anyhow!("{tool}: 'run' is required — the run dir your goal names (`run: cycles/<id>`)")
    })?;
    match RunDir::parse(text) {
        Some(d @ (RunDir::Cycle(_) | RunDir::Replay(_))) => Ok(d),
        _ => bail!(
            "{tool}: 'run' `{text}` is no run dir — give the goal's `run:` value, `cycles/<id>` \
             or `replays/<id>`"
        ),
    }
}

/// Strict object arguments (an unknown key is an error).
pub(crate) fn args<'a>(
    tool: &str,
    args: &'a Value,
    allowed: &[&str],
) -> Result<&'a Map<String, Value>> {
    object_args(tool, args, allowed)
}

/// An optional array of non-empty strings.
pub(crate) fn opt_strings(tool: &str, o: &Map<String, Value>, key: &str) -> Result<Vec<String>> {
    match field(o, key) {
        None => Ok(Vec::new()),
        Some(Value::Array(a)) => a
            .iter()
            .map(|v| match v.as_str().map(str::trim) {
                Some(s) if !s.is_empty() => Ok(s.to_string()),
                _ => bail!("{tool}: '{key}' must be an array of non-empty strings, got {v}"),
            })
            .collect(),
        Some(v) => bail!("{tool}: '{key}' must be an array of strings, got {v}"),
    }
}

/// `submit_*`'s refusal as the tool's error: every problem, one line each.
pub(crate) fn refused(tool: &str, run: &RunDir, errors: &[ValueError]) -> anyhow::Error {
    let lines: Vec<String> = errors.iter().map(|e| format!("- {e}")).collect();
    anyhow!(
        "{tool}: {run} refused the draft ({} problem(s); nothing was written):\n{}",
        errors.len(),
        lines.join("\n")
    )
}

/// Plugin grouping the SOE tools; each catalog row shares it.
pub(crate) struct SoePlugin;

#[async_trait]
impl ToolPlugin for SoePlugin {
    fn name(&self) -> &'static str {
        "soe"
    }

    async fn tools(&self, ctx: &PluginCtx<'_>) -> Result<Vec<Arc<dyn Tool>>> {
        let sections = &ctx.config.sandbox;
        let shared = SoeShared {
            store: open_store(sections),
            sandbox: Arc::clone(sections),
            clock: Arc::new(SystemClock),
            stamp: Stamp::of(ctx.config, ctx.workspace, agent_from_env()),
        };
        Ok(tools(&shared))
    }
}

/// The family's tools over `shared`.
pub(crate) fn tools(shared: &SoeShared) -> Vec<Arc<dyn Tool>> {
    vec![
        Arc::new(view::SoeViewTool::new(shared.clone())),
        Arc::new(propose::SoeProposeTool::new(shared.clone())),
        Arc::new(challenge::SoeChallengeTool::new(shared.clone())),
    ]
}
